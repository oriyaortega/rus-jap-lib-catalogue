import re, json, collections
D='SCRATCH/bib/'
CITY=r'(?:М\.?\s*[—-]\s*Л\.|М\.|Л\.|СПб\.|С\.-Петербург|Пг\.|Петроград|Москва|Владивосток|Хабаровск|Харьков|Киев|Одесса|Казань|Иркутск|Томск|Ташкент|Ростов(?:\s*н/Д\.?|-на-Дону)?|Варшава|Тифлис|Рига|Новосибирск|Свердловск|Горький|Минск|Пермь|Самара|Саратов|Чита|Благовещенск|Нижний Новгород|Н\.\s*Новгород|Токио|Берлин|Ленинград|Дальгиз|Кронштадт|Ревель|Порт-Артур|Харбин|Тбилиси|Ереван|Баку|Алма-Ата|Фрунзе|Душанбе|Петропавловск(?:-Камчатский)?|Южно-Сахалинск|Магадан|Вологда|Ярославль|Воронеж|Курск|Тула|Калуга|Рязань|Смоленск|Новгород|Псков|Архангельск|Мурманск|Петрозаводск|Ульяновск|Пенза|Тамбов|Орёл|Орел|Брянск|Уфа|Оренбург|Челябинск|Омск|Барнаул|Красноярск|Улан-Удэ|Якутск|Николаевск(?:-на-Амуре)?|Симферополь|Севастополь|Николаев|Днепропетровск|Львов|Вильна|Вильно|Ковно|Гельсингфорс|Юрьев|Митава|Кишинев|Житомир|Полтава|Чернигов|Екатеринослав|Ставрополь|Владикавказ|Новочеркасск|Таганрог|Астрахань|Пятигорск|Вятка|Кострома|Тверь|Калинин|Иваново|Владимир)(?![а-яёА-ЯЁ])'
BOOK=re.compile(r'(?:[—\-.]\s*|[.,]\s|—\s*\[)'+CITY+r'\s*[,—:]\s*(?:[^—]{0,90}?)(1[789]\d\d)[.,]\s*(?:[IVXLC\d]+,\s*)?(\d{1,4})\s*(?:с\.|стр\.?|с,|стр,|с\s)')
ARTICLE=re.compile(r'В\s*кн\.|№\s*\d|—\s*«[^»]{2,60}»,\s*[А-Я]|вып\.\s*\d+,\s*с(?:тр)?\.\s*\d+\s*[—-]')
BOOK2=re.compile(r'(?:—\s*\[?|\.\s+\[?)'+CITY+r'\s*[,—:]\s*(?:[^—]{0,90}?)(?:\[?(1[789]\d\d)\]?|б\.\s*г\.)?[.,]?\s*(?:[IVXLC\d]+,\s*)?(?:(\d{1,4})\s*(?:с\.|стр\.?|с,|стр,|с\s)|стр\.\s*(\d{1,4}))')
class M2:
    def __init__(s,m): s.m=m
    def group(s,i): return s.m.group(i) if i==1 else (s.m.group(2) or s.m.group(3))
    def start(s): return s.m.start()
    def end(s): return s.m.end()
def classify(t):
    head=t.split('Рец.')[0].split('Р е ц')[0]
    m=BOOK.search(head)
    if not m:
        m2=BOOK2.search(head)
        if not m2: return None
        m=M2(m2)
    pre=head[:m.start()]
    if ARTICLE.search(pre) or re.search(r'В\s*кн\.',head[:m.end()]): return None
    return {'year':int(m.group(1)) if m.group(1) else None,'pages':int(m.group(2)),'head':head}
if __name__=='__main__':
    for f in ['b1917','b1958','b1973']:
        es=json.load(open(D+f+'.json',encoding='utf-8'))
        bk=[]
        for e in es:
            c=classify(e['text'])
            if c: e.update(c); bk.append(e)
        json.dump(bk,open(D+f+'_books.json','w',encoding='utf-8'),ensure_ascii=False,indent=0)
        secs=collections.Counter(e['sec'].split(' / ')[0][:40] for e in bk)
        print(f,len(es),'books',len(bk))
