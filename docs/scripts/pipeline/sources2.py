def people(names, japanese, order='western'):
    out = []
    for nm in names or []:
        nm = re.sub(r'\s+', ' ', nm).strip(' ,')
        if nm and CYR.search(nm):
            out.append(get_author(nm, japanese=japanese, order=order))
    return [a for a in out if a]


def trs(names):
    out = []
    for nm in names or []:
        out += parse_tr_list(nm, order='western')
    return out


def num(x):
    try:
        return int(re.sub(r'\D', '', str(x))) or None
    except ValueError:
        return None


